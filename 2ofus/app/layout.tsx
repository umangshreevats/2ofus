import type { Metadata } from "next";
import { Rubik, Comfortaa } from "next/font/google";
import "./globals.css";
import { ThemeProvider } from "./theme-provider";
import TopNav from "@/components/landing-page/TopNav";
import { navLocations } from "@/data/info";
import Footer from "@/components/landing-page/Footer";
import { getCurrentUser } from "@/lib/auth";
import { AuthProvider } from "./auth-provider";

export const instant = false;

export const metadata: Metadata = {
    title: "Create Next App",
    description: "Generated by create next app",
};

const rubik = Rubik({
    subsets: ["latin"],
    weight: ["400", "500", "600", "700"],
    variable: "--rubik",
    display: "swap",
});

const comfortaa = Comfortaa({
    subsets: ["latin"],
    weight: ["400", "500", "600", "700"],
    variable: "--comfortaa",
    display: "swap",
});

export default async function RootLayout({
    children,
}: LayoutProps<"/">) {
    const auth = await getCurrentUser();

    return (
        <html className={`${rubik.variable} ${comfortaa.variable}`} lang="en" data-palette="ember" data-theme="light">
            <body className="font-rubik">
                <AuthProvider initialAuth={auth}>
                    <ThemeProvider>
                        <header>
                            <TopNav display={true} navLocations={navLocations} />
                        </header>

                        <main>{children}</main>

                        <footer>
                            <Footer />
                        </footer>
                    </ThemeProvider>
                </AuthProvider>
            </body>
        </html>
    );
}